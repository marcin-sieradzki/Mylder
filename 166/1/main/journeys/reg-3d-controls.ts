import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'

// Regression, moving map: map-3d by keys, the 3D toggle and compass, and right- and Ctrl-drags.
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/en')
  const map = page.locator('[data-vehicles]')
  const region = page.getByRole('region', { name: 'Live map of Copenhagen' })
  const scale = page.getByText(/\d+\s(m|km)$/)
  await expect(page.getByRole('banner').getByText(/^Updated /)).toBeVisible({ timeout: 30000 })
  await step('flat')
  await region.focus()
  for (const key of ['Shift+ArrowUp', 'Shift+ArrowUp', 'Shift+ArrowUp', 'Shift+ArrowRight', 'Shift+ArrowRight']) {
    await page.keyboard.press(key)
    await page.waitForTimeout(500)
  }
  await expect(map).toHaveAttribute('data-tilt', '30', { timeout: 15000 })
  await expect(map).toHaveAttribute('data-heading', '30', { timeout: 15000 })
  await expect(scale).toBeHidden()
  const snap = await (await page.request.get('/api/snapshot')).json()
  await expect(map).toHaveAttribute('data-vehicles', String(snap.trips.filter((t: { cancelled?: boolean }) => !t.cancelled).length))
  await step('tilted 30 turned 30 by keys')
  await page.getByRole('button', { name: 'Centre the map' }).click()
  await expect(map).toHaveAttribute('data-tilt', '0', { timeout: 15000 })
  await expect(map).toHaveAttribute('data-heading', '0', { timeout: 15000 })
  await expect(scale).toBeVisible()
  await step('centred flat north-up')
  const toggle = page.getByRole('button', { name: '3D view' })
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await expect(map).toHaveAttribute('data-tilt', '50', { timeout: 15000 })
  await expect(scale).toBeHidden()
  await page.waitForTimeout(5000)
  await step('3D toggle on')
  await region.focus()
  await page.keyboard.press('Shift+ArrowRight')
  await expect(map).toHaveAttribute('data-heading', '15', { timeout: 15000 })
  const compass = page.getByRole('button', { name: 'Reset to north' })
  await expect(compass).toHaveAccessibleDescription('Map turned away from north')
  await step('turned 15')
  await compass.click()
  await expect(map).toHaveAttribute('data-heading', '0', { timeout: 15000 })
  await expect(map).toHaveAttribute('data-tilt', '50')
  await expect(compass).not.toHaveAccessibleDescription('Map turned away from north')
  await step('back to north')
  await toggle.click()
  await expect(map).toHaveAttribute('data-tilt', '0', { timeout: 15000 })
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await expect(scale).toBeVisible()
  await step('3D toggle off')
  const box = (await region.boundingBox())!
  const x = box.x + box.width / 2
  const y = box.y + box.height / 2
  await page.mouse.move(x, y)
  await page.mouse.down({ button: 'right' })
  await page.mouse.move(x + 150, y, { steps: 10 })
  await page.mouse.up({ button: 'right' })
  await expect(map).not.toHaveAttribute('data-heading', '0', { timeout: 15000 })
  await expect(map).toHaveAttribute('data-tilt', '0')
  await expect(scale).toBeVisible()
  await step('right-drag turned')
  const heading = await map.getAttribute('data-heading')
  await page.mouse.move(x, y)
  await page.mouse.down({ button: 'right' })
  await page.mouse.move(x, y - 60, { steps: 10 })
  await page.mouse.up({ button: 'right' })
  await expect(map).not.toHaveAttribute('data-tilt', '0', { timeout: 15000 })
  await expect(map).toHaveAttribute('data-heading', heading!)
  await expect(scale).toBeHidden()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await step('right-drag tilted')
  await page.getByRole('button', { name: 'Centre the map' }).click()
  await expect(map).toHaveAttribute('data-tilt', '0', { timeout: 15000 })
  await expect(map).toHaveAttribute('data-heading', '0', { timeout: 15000 })
  await page.mouse.move(x, y)
  await page.keyboard.down('Control')
  await page.mouse.down()
  await page.mouse.move(x + 150, y, { steps: 10 })
  await page.mouse.up()
  await page.keyboard.up('Control')
  await expect(map).not.toHaveAttribute('data-heading', '0', { timeout: 15000 })
  await step('ctrl-drag turned')
}
