import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
// Pass rule: arrow keys move between the tabs, each tab panel is named by its tab, and the new words are Danish on /da.
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/en?stop=27532')
  const panel = page.getByRole('dialog', { name: 'Nørreport St.' })
  const dep = panel.getByRole('tab', { name: 'Departures' }), arr = panel.getByRole('tab', { name: 'Arrivals' })
  await expect(dep).toHaveAttribute('aria-selected', 'true')
  await dep.focus()
  await expect(dep).toBeFocused()
  await step('Departures tab focused')
  await page.keyboard.press('ArrowRight')
  await expect(arr).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(arr).toHaveAttribute('aria-selected', 'true')
  await expect(page).toHaveURL(/board=arrivals/)
  await expect(panel.getByRole('tabpanel', { name: 'Arrivals' })).toBeVisible()
  await step('ArrowRight + Enter selects Arrivals')
  await page.keyboard.press('ArrowLeft')
  await expect(dep).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(dep).toHaveAttribute('aria-selected', 'true')
  expect(page.url()).not.toMatch(/board=/)
  await expect(panel.getByRole('tabpanel', { name: 'Departures' })).toBeVisible()
  await step('ArrowLeft + Enter back to Departures')
  await page.goto('/da?stop=27532&board=arrivals')
  const dpanel = page.getByRole('dialog', { name: 'Nørreport St.' })
  await expect(dpanel.getByRole('tab', { name: 'Afgange' })).toBeVisible()
  await expect(dpanel.getByRole('tab', { name: 'Ankomster' })).toHaveAttribute('aria-selected', 'true')
  const dtp = dpanel.getByRole('tabpanel', { name: 'Ankomster' })
  await expect(dtp.getByRole('list', { name: 'Ankomster' })).toBeVisible()
  await expect(dtp).toContainText('Fra Holte St.')
  console.log('DA TABPANEL:\n' + (await dtp.innerText()))
  await step('Danish Arrivals')
  await page.goto('/da?stop=8600683&board=arrivals')
  const h = page.getByRole('dialog', { name: 'Hillerød St.' }).getByRole('tabpanel', { name: 'Ankomster' })
  await expect(h).toContainText('Ingen ankomster de næste 30 minutter for de viste transportformer.')
  console.log('DA EMPTY:\n' + (await h.innerText()))
  await step('Danish empty Arrivals')
}
