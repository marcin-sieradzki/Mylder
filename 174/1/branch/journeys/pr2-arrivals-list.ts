import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
// Pass rule: at Nørreport St. choose Arrivals -> trips arriving in 30 min, each with line, "From" origin, state, countdown, delay;
// Estimated rows with "~"; address gets board=arrivals; source line "Timetable and positions HH:MM:SS"; Departures again drops board.
export default async ({ page, step, expect }: Journey) => {
  const urls: string[] = []
  page.on('request', (r) => urls.push(r.url()))
  await page.goto('/en?stop=27532')
  const panel = page.getByRole('dialog', { name: 'Nørreport St.' })
  await expect(panel.getByRole('list', { name: 'Departures' })).toBeVisible()
  await step('Nørreport St. on Departures')
  await panel.getByRole('tab', { name: 'Arrivals' }).click()
  await expect(page).toHaveURL(/\?stop=27532&board=arrivals$/)
  await expect(panel.getByRole('tab', { name: 'Arrivals' })).toHaveAttribute('aria-selected', 'true')
  const tp = panel.getByRole('tabpanel', { name: 'Arrivals' })
  const list = tp.getByRole('list', { name: 'Arrivals' })
  await expect(list).toBeVisible()
  const rows = list.getByRole('listitem')
  await expect(rows.first()).toBeVisible()
  const texts = await rows.allInnerTexts()
  console.log('ARRIVALS:\n' + texts.join('\n---\n'))
  const first = rows.first()
  await expect(first).toContainText('E')
  await expect(first).toContainText('From Holte St.')
  await expect(first).toContainText(/Live|Estimated|Ageing/)
  await expect(first).toContainText(/\d+ min|Now/)
  await expect(first).toContainText(/\+\d/)
  await expect(first).toContainText(/07:2\d/)
  const est = rows.filter({ hasText: 'Estimated' })
  await expect(est.first()).toContainText(/~\s*\d\d:\d\d/)
  await expect(list).toContainText('From Sundbyvester Plads')
  await expect(list).toContainText('From Herlev Hospital, Sløjfen')
  await expect(tp).toContainText('From the timetable')
  await expect(tp).toContainText(/Timetable and positions \d\d:\d\d:\d\d/)
  console.log('TABPANEL TEXT:\n' + (await tp.innerText()))
  const arrivalCalls = urls.filter((u) => /\/arrivals(\?|$)/.test(u))
  console.log('arrival calls:', arrivalCalls)
  await step('Arrivals listed')
  await panel.getByRole('tab', { name: 'Departures' }).click()
  await expect(page).toHaveURL(/\?stop=27532$/)
  await expect(panel.getByRole('tabpanel', { name: 'Departures' }).getByRole('list', { name: 'Departures' })).toBeVisible()
  await step('back on Departures, board dropped')
}
