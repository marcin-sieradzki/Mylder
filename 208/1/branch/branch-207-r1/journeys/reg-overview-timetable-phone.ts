import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
// overview-sheet `overview-timetable` on a phone, in Danish: lines wrap inside the sheet, no sideways scroll.
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/da')
  await expect(page.getByRole('banner').getByText(/^Opdateret /)).toBeVisible()
  const sheet = page.getByRole('dialog', { name: 'Overblik' })
  await expect(sheet).toBeVisible()
  await step('phone peek')
  await sheet.getByRole('tab', { name: /^Byens puls/ }).click()
  const metro = sheet.getByText('Ingen realtid fra Metroen; placeret efter køreplanen')
  await metro.scrollIntoViewIfNeeded()
  await expect(metro).toBeVisible()
  await step('Metro line on the phone')
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)
  expect(overflow).toBeLessThanOrEqual(0)
  const box = await metro.boundingBox()
  const sbox = await sheet.boundingBox()
  console.log(`metro line ${JSON.stringify(box)} sheet ${JSON.stringify(sbox)}`)
  expect(box!.x + box!.width).toBeLessThanOrEqual(sbox!.x + sbox!.width + 1)
  await page.goto('/en')
  const en = page.getByRole('dialog', { name: 'Overview' })
  await en.getByRole('tab', { name: /^City pulse/ }).click()
  await page.getByRole('button', { name: 'About Mylder' }).click()
  const about = page.getByRole('dialog', { name: 'About Mylder' })
  const fact = about.locator(`xpath=.//dt[normalize-space()="Rejseplanen's realtime"]/following-sibling::dd[1]`)
  await fact.scrollIntoViewIfNeeded()
  await expect(fact).toHaveText('Not connected yet')
  await step('About realtime fact on the phone')
}
