import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
// language-and-about `about-timetable` / `about-open`: About on the timetable source, EN and DA.
export default async ({ page, step, expect }: Journey) => {
  const snap = await (await page.request.get('/api/snapshot')).json()
  const prepared: string = snap.status.timetable.prepared
  const day = Number(prepared.slice(8, 10))
  const fact = (d: ReturnType<typeof page.getByRole>, t: string) =>
    d.locator(`xpath=.//dt[normalize-space()="${t}"]/following-sibling::dd[1]`)
  await page.goto('/en')
  await expect(page.getByRole('banner').getByText(/^Updated /)).toBeVisible()
  await step('map loaded')
  await page.getByRole('button', { name: 'About Mylder' }).click()
  const about = page.getByRole('dialog', { name: 'About Mylder' })
  await expect(about).toBeVisible()
  await step('About open')
  await expect(fact(about, 'Source')).toHaveText("Rejseplanen's timetable, no live positions yet")
  await expect(about.getByText("The positions on this page are the timetable's plan, not reports from the vehicles.")).toBeVisible()
  await expect(about.getByText(/not real/)).toHaveCount(0)
  await expect(about.getByText(new RegExp(`Timetable of ${day} June\\.`))).toBeVisible()
  await expect(about.getByText("Every vehicle is Timetable only for now: live positions aren't connected yet.")).toBeVisible()
  await expect(fact(about, 'Positions')).toHaveText('No position calls')
  await expect(fact(about, "Rejseplanen's realtime")).toHaveText('Not connected yet')
  await expect(fact(about, 'Calls this month')).toHaveText('0')
  await fact(about, 'Calls this month').scrollIntoViewIfNeeded()
  await step('About facts in view')
  await page.keyboard.press('Escape')
  await expect(about).toBeHidden()
  await step('About closed with Esc')
  await page.getByRole('navigation', { name: 'Language' }).getByRole('link', { name: 'Dansk' }).click()
  await expect(page).toHaveURL(/\/da/)
  await expect(page.locator('html')).toHaveAttribute('lang', 'da')
  await step('switched to Danish')
  await page.getByRole('button', { name: 'Om Mylder' }).click()
  const om = page.getByRole('dialog', { name: 'Om Mylder' })
  await expect(om).toBeVisible()
  await expect(fact(om, 'Kilde')).toHaveText('Rejseplanens køreplan, endnu ingen livepositioner')
  await expect(fact(om, 'Rejseplanens realtid')).toHaveText('Ikke koblet på endnu')
  await expect(om.getByText('Positionerne på denne side er køreplanens plan, ikke meldinger fra køretøjerne.')).toBeVisible()
  await expect(om.getByText(new RegExp(`Køreplan fra ${day}\\. juni\\.`))).toBeVisible()
  await fact(om, 'Rejseplanens realtid').scrollIntoViewIfNeeded()
  await step('Om Mylder open')
}
