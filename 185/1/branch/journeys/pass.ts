import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
import { hitAt, realTap, raiseOverview, tripKey } from './lib.ts'

type Size = { width: number; height: number } | undefined

// P1: a stop link on a phone opens the stop's sheet in front; its tabs and rows take real taps.
export async function stopLinkInFront({ page, step, expect }: Journey, size: Size) {
  if (size) await page.setViewportSize(size)
  const log: string[] = []
  await page.goto('/en?stop=27532')
  const overview = page.getByRole('dialog', { name: 'Overview' })
  const panel = page.getByRole('dialog', { name: 'Nørreport St.' })
  await expect(panel).toBeVisible()
  await expect(panel.getByRole('list', { name: 'Departures' }).getByRole('listitem').first()).toBeVisible()
  await expect(overview).toBeAttached()
  console.log('overview box', JSON.stringify(await overview.boundingBox()), 'panel box', JSON.stringify(await panel.boundingBox()))
  await step('stop link opened, Overview at peek')
  const head = await hitAt(page, panel.getByRole('heading', { name: 'Nørreport St.' }))
  console.log('heading hit', JSON.stringify(head))
  expect(head.dialog, 'the stop heading is in front').toBe('Nørreport St.')
  await realTap(page, panel.getByRole('tab', { name: 'Arrivals' }), 'Nørreport St.', log)
  await expect(page).toHaveURL(/\?stop=27532&board=arrivals$/)
  await expect(panel.getByRole('tab', { name: 'Arrivals' })).toHaveAttribute('aria-selected', 'true')
  await expect(panel.getByRole('tabpanel', { name: 'Arrivals' }).getByRole('list', { name: 'Arrivals' })).toBeVisible()
  await step('Arrivals tab tapped')
  await realTap(page, panel.getByRole('tab', { name: 'Departures' }), 'Nørreport St.', log)
  await expect(page).toHaveURL(/\?stop=27532$/)
  await expect(panel.getByRole('list', { name: 'Departures' })).toBeVisible()
  await step('Departures tab tapped')
  const row = panel.getByRole('list', { name: 'Departures' }).getByRole('button').first()
  const rowName = await row.getAttribute('aria-label') ?? await row.innerText()
  console.log('row', rowName)
  await realTap(page, row, 'Nørreport St.', log)
  await expect(page).toHaveURL(/[?&]trip=/)
  await expect(page.getByRole('dialog', { name: / to / })).toBeVisible()
  await step('departure row tapped, vehicle open')
  await expect(overview).toBeAttached()
}

