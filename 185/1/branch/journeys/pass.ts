// P4: tapping a stop on the map on a phone, Overview left open, opens the stop's sheet.
export async function mapTap({ page, step, expect }: Journey, size: Size) {
  if (size) await page.setViewportSize(size)
  await page.goto('/en?map=15.00/55.6925/12.58779')
  const overview = page.getByRole('dialog', { name: 'Overview' })
  await expect(overview).toBeVisible()
  await expect(page.getByRole('banner').getByText(/^Updated /)).toBeVisible()
  await step('map at Østerport, Overview at peek')
  const vp = page.viewportSize()!
  const panel = page.getByRole('dialog', { name: 'Østerport St.' })
  await expect(async () => {
    await page.touchscreen.tap(vp.width / 2, vp.height / 2)
    await expect(panel).toBeVisible({ timeout: 2000 })
  }).toPass({ timeout: 30000 })
  await expect(page).toHaveURL(/[?&]stop=8600650/)
  await expect(panel).toHaveAttribute('data-anchor', 'bottom')
  await expect(panel.getByRole('list', { name: 'Departures' })).toBeVisible()
  await expect(overview).toBeAttached()
  await step('stop sheet open from map tap')
  // Not the rule, recorded: is the stop's sheet in front?
  const hit = await hitAt(page, panel.getByRole('tab', { name: 'Arrivals' }))
  console.log('EXTRA map-tap Arrivals tab hit', JSON.stringify(hit))
}

// P5: Overview full height -> Vehicles row -> vehicle panel -> Close: the Overview comes back usable.
export async function overviewRoundtrip({ page, step, expect }: Journey, size: Size) {
  if (size) await page.setViewportSize(size)
  const log: string[] = []
  await page.goto('/en')
  const overview = page.getByRole('dialog', { name: 'Overview' })
  await expect(overview).toBeVisible()
  await expect(page.getByRole('banner').getByText(/^Updated /)).toBeVisible()
  await page.waitForTimeout(500)
  await raiseOverview(page)
  const box = await overview.boundingBox()
  console.log('overview raised box', JSON.stringify(box))
  expect(box!.y, 'Overview at full height').toBeLessThan(100)
  await step('Overview raised to full height')
  await realTap(page, overview.getByRole('tab', { name: /^Vehicles/ }), 'Overview', log)
  await expect(page).toHaveURL(/tab=vehicles/)
  const table = overview.getByRole('table', { name: 'Vehicles' })
  await expect(table).toBeVisible()
  await step('Vehicles list')
  const link = table.getByRole('row').nth(1).getByRole('link').first()
  const linkText = await link.innerText()
  console.log('row link', linkText)
  await realTap(page, link, 'Overview', log)
  const vehicle = page.getByRole('dialog', { name: / to / })
  await expect(vehicle).toBeVisible()
  await expect(page).toHaveURL(/trip=/)
  await page.waitForTimeout(600)
  console.log('vehicle box', JSON.stringify(await vehicle.boundingBox()), 'overview box', JSON.stringify(await overview.boundingBox()))
  await step('vehicle panel open')
  await realTap(page, vehicle.getByRole('button', { name: 'Close' }), / to /, log)
  await expect(vehicle).toBeHidden()
  expect(page.url()).not.toContain('trip=')
  await page.waitForTimeout(600)
  console.log('overview box after close', JSON.stringify(await overview.boundingBox()))
  await step('vehicle panel closed')
  await expect(overview).toBeVisible()
  for (const target of [overview.getByRole('heading', { name: 'Overview' }), overview.getByRole('button', { name: 'Close' })]) {
    const h = await hitAt(page, target)
    console.log('overview hit', JSON.stringify(h))
    expect(h.insideTarget && h.dialog === 'Overview', `Overview ${await target.innerText().catch(() => '')} reachable`).toBe(true)
  }
  await realTap(page, overview.getByRole('tab', { name: 'City pulse' }), 'Overview', log)
  await expect(overview.getByRole('tab', { name: 'City pulse' })).toHaveAttribute('aria-selected', 'true')
  await step('City pulse tapped after close')
  await realTap(page, overview.getByRole('tab', { name: /^Disruptions/ }), 'Overview', log)
  await expect(overview.getByRole('tab', { name: /^Disruptions/ })).toHaveAttribute('aria-selected', 'true')
  await step('Disruptions tapped after close')
  await realTap(page, overview.getByRole('button', { name: 'Close' }), 'Overview', log)
  await expect(overview).toBeHidden()
  await step('Overview closed with its Close')
}

// P6: a ?trip= link on a phone opens the vehicle panel in front.
export async function tripLink({ page, step, expect }: Journey, size: Size) {
  if (size) await page.setViewportSize(size)
  const log: string[] = []
  const trip = await tripKey(page, (t) => t.mode === 'bus')
  console.log('trip', trip.key, trip.line, trip.headsign)
  await page.goto(`/en?trip=${encodeURIComponent(trip.key)}`)
  const vehicle = page.getByRole('dialog', { name: new RegExp(`${trip.line} to ${trip.headsign}`) })
  await expect(vehicle).toBeVisible()
  await expect(page.getByRole('dialog', { name: 'Overview' })).toBeAttached()
  await page.waitForTimeout(600)
  await step('trip link opened')
  const stops = await hitAt(page, vehicle.getByRole('list', { name: 'Stops' }))
  console.log('stops hit', JSON.stringify(stops))
  expect(stops.dialog, 'vehicle panel in front').toMatch(/ to /)
  await realTap(page, vehicle.getByRole('button', { name: 'Show whole line' }), / to /, log)
  const chip = page.getByRole('button', { name: /^Showing: line .* · Clear$/ })
  await expect(chip).toBeVisible()
  await step('Show whole line tapped')
  await realTap(page, vehicle.getByRole('button', { name: 'Close' }), / to /, log)
  await expect(vehicle).toBeHidden()
  expect(page.url()).not.toContain('trip=')
  await step('vehicle closed')
}

