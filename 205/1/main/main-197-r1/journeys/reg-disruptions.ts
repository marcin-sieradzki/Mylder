// Regression: disruptions recipes List, Footer, Show on map, tilted, Danish on the weekday recording.
import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/en')
  await expect(page.locator('[data-vehicles]')).not.toHaveAttribute('data-vehicles', '0', { timeout: 30000 })
  const sheet = page.getByRole('dialog', { name: 'Overview' })
  await sheet.getByRole('tab', { name: /^Disruptions/ }).click()
  const active = sheet.getByRole('list', { name: 'Active now' })
  await expect(active).toContainText('Færre S-tog mellem København H og Hellerup')
  await expect(active).toContainText('Linje 5C kører en anden rute ved Langebro')
  await expect(sheet.getByRole('list', { name: 'Later' })).toContainText('Ingen S-tog mellem Hellerup og Holte i weekenden')
  await expect(sheet.getByText('Messages from Rejseplanen, checked 07:20.')).toBeVisible()
  await step('list and footer')
  await active.getByRole('listitem').first().getByRole('button', { name: 'Show on map' }).click()
  const chip = page.getByRole('button', { name: /^Showing: .* · Clear$/ })
  await expect(chip).toBeVisible()
  await step('show on map')
  await chip.click()
  await expect(chip).toHaveCount(0)
  await step('cleared')
  await page.goto('/en?tab=disruptions&map=13.00/55.67000/12.57000/-30.0/50.0')
  await expect(page.locator('[data-vehicles]')).not.toHaveAttribute('data-vehicles', '0', { timeout: 30000 })
  const five = page.getByRole('dialog', { name: 'Overview' }).getByRole('listitem').filter({ hasText: 'Linje 5C' })
  await five.getByRole('button', { name: 'Show on map' }).click()
  await expect(page).toHaveURL(/map=15\.00\/[^&]*\/-30\.0\/50\.0/, { timeout: 15000 })
  await page.waitForTimeout(800)
  await step('5C shown, tilted')
  await page.goto('/da?tab=disruptions')
  const da = page.getByRole('dialog', { name: 'Overblik' })
  await expect(da.getByRole('list', { name: 'Aktuelle nu' })).toContainText('Færre S-tog mellem København H og Hellerup')
  await step('Danish')
}
