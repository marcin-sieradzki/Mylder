// Pass rule 9: the new words in Danish, on each Overview tab.
import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/da')
  await expect(page.locator('html')).toHaveAttribute('lang', 'da')
  await expect(page.locator('[data-vehicles]')).not.toHaveAttribute('data-vehicles', '0', { timeout: 30000 })
  const sheet = page.getByRole('dialog', { name: 'Overblik' })
  await expect(sheet).toBeVisible()
  await step('Byens puls')
  const pulse = sheet.getByRole('tabpanel')
  await expect(pulse.getByRole('region', { name: 'I bevægelse, efter transportform' })).toBeVisible()
  await expect(pulse.getByText('Ingen livepositioner endnu; placeret efter køreplanen', { exact: false }).first()).toBeVisible()
  const ptext = await pulse.innerText()
  expect(ptext).toContain('—')
  expect(ptext).not.toMatch(/\d+\s*%/)
  expect(ptext).not.toMatch(/gennemsnitlig forsinkelse/i)
  expect(ptext).not.toMatch(/Rejseplanen ·/)
  expect(ptext).not.toMatch(/sat på pause|pause/i)
  const placed = sheet.locator('time', { hasText: /^placeret \d\d:\d\d:\d\d$/ })
  expect(await placed.first().locator('xpath=..').innerText()).toMatch(/^Køreplan\s·\splaceret \d\d:\d\d:\d\d$/)
  for (const m of await pulse.getByRole('meter').all()) await expect(m).toHaveAttribute('data-color', 'neutral')
  console.log('pulse text: ' + ptext.replace(/\n/g, ' / ').slice(0, 900))
  await pulse.getByRole('region', { name: 'I bevægelse, efter transportform' }).scrollIntoViewIfNeeded()
  await step('Byens puls, efter transportform')

  await sheet.getByRole('tab', { name: /^Køretøjer/ }).click()
  const table = sheet.getByRole('table')
  await expect(table).toBeVisible()
  await step('Køretøjer')
  const body = table.getByRole('rowgroup').nth(1).getByRole('row')
  const rows = await body.evaluateAll((els) => els.map((r) => Array.from(r.children).map((c) => (c as HTMLElement).innerText.trim())))
  expect(rows.length).toBeGreaterThan(0)
  expect(rows.filter((c) => !c[0] || !c[1] || c[c.length - 1] !== 'Kun køreplan')).toEqual([])
  const vplaced = sheet.locator('time', { hasText: /^placeret \d\d:\d\d:\d\d$/ })
  expect(await vplaced.first().locator('xpath=..').innerText()).toMatch(/^Køreplan\s·\splaceret \d\d:\d\d:\d\d$/)

  await sheet.getByRole('tab', { name: /^Driftsforstyrrelser/ }).click()
  await expect(sheet.getByRole('tabpanel')).toHaveText('Driftsmeddelelser kommer med Rejseplanens liveforbindelse, som ikke er koblet på endnu.')
  await expect(sheet.getByRole('tabpanel').getByRole('list')).toHaveCount(0)
  await step('Driftsforstyrrelser')
}
