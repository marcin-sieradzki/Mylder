// Regression: overview-sheet recipes Pulse, List, Search, Row on the weekday recording.
import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/en')
  const map = page.locator('[data-vehicles]')
  await expect(map).not.toHaveAttribute('data-vehicles', '0', { timeout: 30000 })
  const sheet = page.getByRole('dialog', { name: 'Overview' })
  await expect(sheet.getByRole('group', { name: 'On the move' })).toHaveText(/\d/)
  await step('pulse')
  await sheet.getByRole('tab', { name: /^Vehicles/ }).click()
  await expect(page).toHaveURL(/[?&]tab=vehicles/)
  const table = sheet.getByRole('table', { name: 'Vehicles' })
  await expect.poll(async () => (await table.getByRole('row').count()) - 1 - Number(await map.getAttribute('data-vehicles')), { timeout: 30000 }).toBe(0)
  await step('list')
  await sheet.getByLabel('Search lines and destinations').fill('5C')
  const body = table.getByRole('rowgroup').nth(1).getByRole('row')
  await expect(body.first()).toBeVisible()
  for (const r of await body.all()) await expect(r.getByRole('rowheader').first()).toHaveText('5C')
  await step('search 5C')
  await sheet.getByLabel('Search lines and destinations').fill('zzz')
  await expect(sheet.getByText('No vehicles match.')).toBeVisible()
  await step('search zzz')
  await sheet.getByLabel('Search lines and destinations').fill('')
  const link = body.first().getByRole('link')
  const name = await link.innerText()
  await link.click()
  await expect(page).toHaveURL(/[?&]trip=/)
  await expect(page.getByRole('dialog').filter({ hasText: name }).first()).toBeVisible()
  await step('row opened vehicle detail')
}
