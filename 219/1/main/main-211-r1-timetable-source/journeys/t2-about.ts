import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
import { dump } from './dump.ts'
const J = 't2-about'
export default async ({ page, step, expect }: Journey) => {
  const snap = await (await page.request.get('/api/snapshot')).json()
  await page.goto('/en')
  await expect(page.locator('[data-vehicles]')).not.toHaveAttribute('data-vehicles', '0')
  await step('en before about')
  await page.getByRole('link', { name: 'Rejseplanen' }).click()
  const d = page.getByRole('dialog', { name: 'About Mylder' })
  await expect(d).toBeVisible()
  await expect(d).toContainText("Rejseplanen's timetable, no live positions yet")
  await expect(d).toContainText('The positions on this page are the timetable\'s plan, not reports from the vehicles.')
  await expect(d).not.toContainText('not real')
  await expect(d).toContainText(/Timetable data: Rejseplanen, under CC BY 4\.0\. Timetable of .+\./)
  await expect(d).toContainText("Every vehicle is Timetable only for now: live positions aren't connected yet.")
  await expect(d).toContainText('No position calls')
  await expect(d).toContainText('Not connected yet')
  await page.waitForTimeout(1000)
  await step('en about')
  dump(J, 'en.about', await d.innerText())
  dump(J, 'prepared', String(snap.status?.timetable?.prepared))
  await page.keyboard.press('Escape')
  await expect(d).toBeHidden()
  await page.goto('/da')
  await page.getByRole('button', { name: 'Om Mylder' }).click()
  const dd = page.getByRole('dialog', { name: 'Om Mylder' })
  await expect(dd).toContainText('Rejseplanens køreplan, endnu ingen livepositioner')
  await expect(dd).toContainText('Ikke koblet på endnu')
  await expect(dd).toContainText('Positionerne på denne side er køreplanens plan, ikke meldinger fra køretøjerne.')
  await expect(dd).toContainText(/Køreplansdata: Rejseplanen, under CC BY 4\.0\. Køreplan fra .+\./)
  await page.waitForTimeout(1000)
  await step('da about')
  dump(J, 'da.about', await dd.innerText())
}
