import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
import { dump } from './dump.ts'
const J = 't3-pulse'
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/en')
  await expect(page.locator('[data-vehicles]')).not.toHaveAttribute('data-vehicles', '0')
  const sheet = page.getByRole('dialog', { name: 'Overview' })
  await expect(async () => {
    const snap = await (await page.request.get('/api/snapshot')).json()
    await expect(sheet.getByRole('group', { name: 'On the move' })).toContainText(`of ${snap.trips.length} in service`, { timeout: 1000 })
  }).toPass({ timeout: 30000 })
  await expect(sheet.getByRole('region', { name: 'On the move, by mode' })).toBeVisible()
  await expect(sheet.getByRole('group', { name: 'Average delay' })).toHaveCount(0)
  await expect(sheet).toContainText('No live positions yet; placed from the timetable')
  await expect(sheet).toContainText('No realtime from the Metro; placed from the timetable')
  await expect(sheet.locator('time', { hasText: /^placed / })).toBeVisible()
  await expect(sheet).toContainText(/Vehicles in service today/)
  await expect(sheet).not.toContainText(/paused|Rejseplanen ·/)
  await page.waitForTimeout(800)
  await step('en city pulse')
  dump(J, 'en.pulse', await sheet.innerText())
  await sheet.getByRole('tab', { name: /^Vehicles/ }).click()
  await expect(page).toHaveURL(/tab=vehicles/)
  const table = sheet.getByRole('table', { name: 'Vehicles' })
  await expect.poll(async () => (await table.getByRole('row').count()) - 1).toBe(Number(await page.locator('[data-vehicles]').getAttribute('data-vehicles')))
  await expect(table.getByRole('columnheader', { name: 'Delay' })).toHaveCount(0)
  await expect(sheet).toContainText(/Timetable\s·\splaced \d\d:\d\d:\d\d/)
  await step('en vehicles')
  dump(J, 'en.vehicles', await sheet.innerText())
  await sheet.getByRole('tab', { name: /^Disruptions/ }).click()
  const tp = sheet.getByRole('tabpanel')
  await expect(tp).toHaveText("Disruption messages come with Rejseplanen's live connection, which isn't connected yet.")
  await expect(sheet.getByRole('tab', { name: /^Disruptions/ })).toHaveText('Disruptions')
  await step('en disruptions')
  dump(J, 'en.disruptions', await sheet.innerText())
  await page.goto('/da')
  const ds = page.getByRole('dialog', { name: 'Overblik' })
  await expect(ds).toContainText('I bevægelse, efter transportform')
  await expect(ds).toContainText('Ingen livepositioner endnu; placeret efter køreplanen')
  await expect(ds).toContainText('Ingen realtid fra Metroen; placeret efter køreplanen')
  await expect(ds).not.toContainText('placeret ud fra')
  await page.waitForTimeout(800)
  await step('da city pulse')
  dump(J, 'da.pulse', await ds.innerText())
  await page.goto('/da?tab=disruptions')
  await expect(page.getByRole('dialog', { name: 'Overblik' })).toContainText('Driftsmeddelelser kommer med Rejseplanens liveforbindelse, som ikke er koblet på endnu.')
  await step('da disruptions')
}
