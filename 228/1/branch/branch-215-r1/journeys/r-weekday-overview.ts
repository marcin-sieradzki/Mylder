import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/en')
  const sheet = page.getByRole('dialog', { name: 'Overview' })
  const otm = sheet.getByRole('group', { name: 'On the move' })
  await expect(otm).toContainText(/\d/)
  const pulse = await sheet.getByRole('tabpanel').innerText()
  console.log('pulse', JSON.stringify(pulse.slice(0, 2500)))
  await step('city pulse')
  await sheet.getByRole('tab', { name: /^Vehicles/ }).click()
  await expect(page).toHaveURL(/tab=vehicles/)
  const table = sheet.getByRole('table', { name: 'Vehicles' })
  await expect.poll(async () => (await table.getByRole('row').count()) - 1 - Number(await page.locator('[data-vehicles]').getAttribute('data-vehicles')), { timeout: 20_000 }).toBe(0)
  await step('vehicles list')
  await sheet.getByLabel('Search lines and destinations').fill('5C')
  const rows = table.getByRole('row')
  await expect.poll(async () => rows.count()).toBeGreaterThan(1)
  const n = await rows.count()
  for (let i = 1; i < n; i++) await expect(rows.nth(i)).toContainText('5C')
  await step('search 5C')
  await sheet.getByLabel('Search lines and destinations').fill('zzz')
  await expect(sheet.getByText('No vehicles match.')).toBeVisible()
  await step('no match')
}
