import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
import { ready, focusMap, press, camera } from './lib.ts'
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/en')
  await ready(page, expect)
  await page.getByRole('dialog', { name: 'Overview' }).getByRole('tab', { name: /^Vehicles/ }).click()
  await page.getByRole('table', { name: 'Vehicles' }).getByRole('link').first().click()
  const panel = page.getByRole('dialog', { name: / to / })
  await expect(panel).toBeVisible()
  const follow = panel.getByRole('button', { name: 'Follow' })
  await follow.click()
  await expect(follow).toHaveAttribute('aria-pressed', 'true')
  await page.waitForTimeout(4000)
  await step('following')
  await expect(follow).toHaveAttribute('aria-pressed', 'true')
  await focusMap(page)
  await page.waitForTimeout(1000)
  await expect(follow).toHaveAttribute('aria-pressed', 'true')
  await step('map focused, still following')
  await press(page, 'Shift+ArrowUp', 1, 1500)
  console.log('after Shift+Up', JSON.stringify(await camera(page)))
  await step('Shift+Up pressed')
  await expect(follow).not.toHaveAttribute('aria-pressed', 'true', { timeout: 5000 })
  await expect(page.locator('[data-vehicles]')).toHaveAttribute('data-tilt', '10')
  // and a turn key on its own, after following again
  await follow.click()
  await expect(follow).toHaveAttribute('aria-pressed', 'true')
  await page.waitForTimeout(3000)
  await step('following again')
  await focusMap(page)
  await press(page, 'Shift+ArrowLeft', 1, 1500)
  console.log('after Shift+Left', JSON.stringify(await camera(page)))
  await step('Shift+Left pressed')
  await expect(follow).not.toHaveAttribute('aria-pressed', 'true', { timeout: 5000 })
}
