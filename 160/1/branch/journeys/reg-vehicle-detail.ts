import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
import { ready } from './lib.ts'
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/en')
  await ready(page, expect)
  await page.getByRole('dialog', { name: 'Overview' }).getByRole('tab', { name: /^Vehicles/ }).click()
  await page.getByRole('table', { name: 'Vehicles' }).getByRole('link').nth(5).click()
  const panel = page.getByRole('dialog', { name: / to / })
  await expect(panel).toBeVisible()
  await expect(page).toHaveURL(/trip=/)
  await expect(panel.getByText('Delay', { exact: true })).toBeVisible()
  await expect(panel.getByText('Last seen', { exact: true })).toBeVisible()
  await expect(panel.getByText('Next stop', { exact: true }).first()).toBeVisible()
  await expect(panel.getByRole('list', { name: 'Stops' })).toBeVisible()
  await step('trip panel from the list')
  const follow = panel.getByRole('button', { name: 'Follow' })
  await follow.click()
  await expect(follow).toHaveAttribute('aria-pressed', 'true')
  await page.waitForTimeout(2000)
  await step('following')
  await panel.getByRole('button', { name: 'Show whole line' }).click()
  const chip = page.getByRole('button', { name: /^Showing: line .* · Clear$/ })
  await expect(chip).toBeVisible()
  await page.waitForTimeout(1500)
  await step('whole line shown')
  await chip.click()
  await expect(chip).toBeHidden()
  await page.keyboard.press('Escape')
  await expect(panel).toBeHidden()
  await expect(page).not.toHaveURL(/trip=/)
  await step('closed')
  await page.goto('/en?trip=nothing')
  await expect(page.getByRole('dialog', { name: 'Trip not found' })).toBeVisible()
  await step('trip not found')
}
