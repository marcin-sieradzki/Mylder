import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
import { ready, map, scale, focusMap, press, camera } from './lib.ts'
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/en')
  await ready(page, expect)
  await focusMap(page)
  await step('flat, map focused')
  await press(page, 'Shift+ArrowUp')
  await expect(map(page)).toHaveAttribute('data-tilt', '10', { timeout: 10000 })
  await expect(scale(page)).toBeHidden()
  await page.waitForTimeout(800)
  await step('Shift+Up: tilted one step (10)')
  await press(page, 'Shift+ArrowDown')
  await expect(map(page)).toHaveAttribute('data-tilt', '0', { timeout: 10000 })
  await expect(scale(page)).toBeVisible()
  await step('Shift+Down: flat again, scale bar back')
  for (let i = 0; i < 8; i++) await press(page, 'Shift+ArrowUp', 1, 700)
  await page.waitForTimeout(1500)
  await expect(map(page)).toHaveAttribute('data-tilt', '60', { timeout: 10000 })
  await step('eight Shift+Up: tilt stops at 60')
  console.log('after 8 up', JSON.stringify(await camera(page)))
  await press(page, 'Shift+ArrowUp', 2, 700)
  await page.waitForTimeout(1500)
  await expect(map(page)).toHaveAttribute('data-tilt', '60')
  await step('two more Shift+Up: still 60')
  const c = await camera(page)
  console.log('after 10 up', JSON.stringify(c))
  expect(c.vehicles).toBe('17')
}
