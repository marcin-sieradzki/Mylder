import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
import { ready, map, scale, camera, canvasMiddle } from './lib.ts'
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/en')
  await ready(page, expect)
  const { x, y } = await canvasMiddle(page)
  const cx = x + 150 // right of the Overview sheet
  await step('flat, north-up')
  // right-drag sideways: turns
  await page.mouse.move(cx, y)
  await page.mouse.down({ button: 'right' })
  await page.mouse.move(cx + 150, y, { steps: 10 })
  await page.mouse.up({ button: 'right' })
  await expect(map(page)).not.toHaveAttribute('data-heading', '0', { timeout: 10000 })
  await page.waitForTimeout(1000)
  console.log('right-drag sideways', JSON.stringify(await camera(page)))
  await step('right-drag sideways: turned, still flat')
  await expect(map(page)).toHaveAttribute('data-tilt', '0')
  await expect(scale(page)).toBeVisible()
  const h1 = await map(page).getAttribute('data-heading')
  // right-drag up: tilts
  await page.mouse.move(cx, y)
  await page.mouse.down({ button: 'right' })
  await page.mouse.move(cx, y - 60, { steps: 10 })
  await page.mouse.up({ button: 'right' })
  await expect(map(page)).not.toHaveAttribute('data-tilt', '0', { timeout: 10000 })
  await page.waitForTimeout(1000)
  console.log('right-drag up', JSON.stringify(await camera(page)))
  await step('right-drag up: tilted, heading kept, scale bar hidden')
  await expect(scale(page)).toBeHidden()
  // back to flat, north-up
  await page.getByRole('button', { name: 'Centre the map' }).click()
  await expect(map(page)).toHaveAttribute('data-tilt', '0', { timeout: 10000 })
  await expect(map(page)).toHaveAttribute('data-heading', '0', { timeout: 10000 })
  await page.waitForTimeout(1000)
  await step('reset')
  // Ctrl + left-drag sideways: turns
  await page.mouse.move(cx, y)
  await page.keyboard.down('Control')
  await page.mouse.down()
  await page.mouse.move(cx + 150, y, { steps: 10 })
  await page.mouse.up()
  await page.keyboard.up('Control')
  await expect(map(page)).not.toHaveAttribute('data-heading', '0', { timeout: 10000 })
  await page.waitForTimeout(1000)
  console.log('ctrl-drag sideways', JSON.stringify(await camera(page)))
  await step('Ctrl-drag sideways: turned')
  await expect(map(page)).toHaveAttribute('data-tilt', '0')
  // Ctrl + left-drag up: tilts
  await page.mouse.move(cx, y)
  await page.keyboard.down('Control')
  await page.mouse.down()
  await page.mouse.move(cx, y - 60, { steps: 10 })
  await page.mouse.up()
  await page.keyboard.up('Control')
  await expect(map(page)).not.toHaveAttribute('data-tilt', '0', { timeout: 10000 })
  await page.waitForTimeout(1000)
  console.log('ctrl-drag up', JSON.stringify(await camera(page)))
  await step('Ctrl-drag up: tilted')
  await expect(scale(page)).toBeHidden()
  expect(await map(page).getAttribute('data-vehicles')).toBe(String((await (await page.request.get('/api/snapshot')).json()).trips.filter((t: any) => t.state !== 'cancelled').length))
}
