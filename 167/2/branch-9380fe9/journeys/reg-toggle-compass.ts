import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
import { ready, region } from './lib.ts'

// Regression, moving-map map-3d "3D toggle and compass".
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/en')
  await ready(page, expect)
  const v = page.locator('[data-vehicles]')
  const scale = page.getByText(/\d+\s(m|km)$/)
  const toggle = page.getByRole('button', { name: '3D view' })
  const compass = page.getByRole('button', { name: 'Reset to north' })
  await step('flat')
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await expect(v).toHaveAttribute('data-tilt', '50', { timeout: 15000 })
  await expect(scale).toBeHidden()
  await page.waitForTimeout(1000)
  await step('3D view on, tilt 50')
  await region(page).focus()
  await page.keyboard.press('Shift+ArrowRight')
  await expect(v).toHaveAttribute('data-heading', '15', { timeout: 15000 })
  await expect(compass).toHaveAccessibleDescription('Map turned away from north')
  await page.waitForTimeout(1000)
  await step('turned 15, compass needle turned')
  await compass.click()
  await expect(v).toHaveAttribute('data-heading', '0', { timeout: 15000 })
  await expect(v).toHaveAttribute('data-tilt', '50')
  await expect(compass).toHaveAccessibleDescription('')
  await page.waitForTimeout(1000)
  await step('reset to north, still tilted')
  await toggle.click()
  await expect(v).toHaveAttribute('data-tilt', '0', { timeout: 15000 })
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await expect(scale).toBeVisible()
  await page.waitForTimeout(1000)
  await step('flat again')
  await region(page).focus()
  await page.keyboard.press('Shift+ArrowUp')
  await expect(v).toHaveAttribute('data-tilt', '10', { timeout: 15000 })
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await step('Shift+Up shows the toggle pressed')
}
