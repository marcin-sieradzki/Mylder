import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/en')
  const sheet = page.getByRole('dialog', { name: 'Overview' })
  await step('map')
  await sheet.getByRole('tab', { name: /^Disruptions/ }).click()
  await expect(page).toHaveURL(/tab=disruptions/)
  await expect(sheet.getByRole('list', { name: 'Active now' })).toContainText('Færre S-tog mellem København H og Hellerup')
  await expect(sheet.getByRole('list', { name: 'Active now' })).toContainText('Linje 5C kører en anden rute ved Langebro')
  await expect(sheet.getByRole('list', { name: 'Later' })).toContainText('Ingen S-tog mellem Hellerup og Holte i weekenden')
  await expect(sheet.getByText('Messages from Rejseplanen, checked 07:20.')).toBeVisible()
  await expect(sheet.getByText(/Delays from Rejseplanen not updated/)).toHaveCount(0)
  await step('disruptions list')
  await sheet.getByRole('list', { name: 'Active now' }).getByRole('button', { name: 'Show on map' }).first().click()
  const chip = page.getByRole('button', { name: /^Showing: .* · Clear$/ })
  await expect(chip).toBeVisible()
  await step('shown on map')
  await chip.click()
  await expect(chip).toBeHidden()
  await step('cleared')
  await page.goto('/da?tab=disruptions')
  const da = page.getByRole('dialog', { name: 'Overblik' })
  await expect(da.getByRole('list', { name: 'Aktuelle nu' })).toContainText('Færre S-tog mellem København H og Hellerup')
  await expect(da.getByText(/Forsinkelser fra Rejseplanen ikke opdateret/)).toHaveCount(0)
  await step('danish disruptions')
}
