import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/en?stop=27532')
  const panel = page.getByRole('dialog', { name: /Nørreport St\./ })
  await expect(panel).toBeVisible({ timeout: 20000 })
  await expect(panel.getByRole('tablist', { name: 'Departures and arrivals' })).toBeVisible()
  await expect(panel.getByRole('tab', { name: 'Departures' })).toHaveAttribute('aria-selected', 'true')
  await expect(panel.getByRole('list', { name: 'Departures' }).getByRole('listitem').first()).toBeVisible()
  await step('Nørreport departures')
  await panel.getByRole('tab', { name: 'Arrivals' }).click()
  await expect(page).toHaveURL(/board=arrivals/)
  await expect(panel.getByRole('list', { name: 'Arrivals' })).toBeVisible()
  await expect(panel.getByText(/Timetable and positions \d\d:\d\d/)).toBeVisible()
  await step('Nørreport arrivals')
  await page.goto('/en?stop=8600783&board=arrivals')
  const syd = page.getByRole('dialog', { name: /København Syd St\./ })
  await expect(syd.getByText(/arrivals \d\d:\d\d/)).toBeVisible({ timeout: 20000 })
  await expect(syd.getByText('Track 8').first()).toBeVisible()
  await step('København Syd arrivals from the board')
  await page.goto('/en?stop=48645')
  const ref = page.getByRole('dialog', { name: /Refshaleøen/ })
  const standing = ref.getByRole('region', { name: 'At the platforms now' })
  await expect(standing).toContainText('991', { timeout: 20000 })
  await step('Refshaleøen standing')
  await page.goto('/en?stop=nowhere')
  await expect(page.getByRole('dialog', { name: 'Stop not found' })).toBeVisible()
  await step('stop not found')
}
