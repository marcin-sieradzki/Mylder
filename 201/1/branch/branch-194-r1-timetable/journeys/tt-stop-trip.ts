import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
export default async ({ page, step, expect }: Journey) => {
  const before = await (await page.request.get('/api/snapshot')).json()
  expect(before.status.calls).toEqual([])
  // Nørreport St. in the deployed timetable
  await page.goto('/en?stop=6584')
  const panel = page.getByRole('dialog', { name: /Nørreport St\./ })
  await expect(panel).toBeVisible({ timeout: 30000 })
  const deps = panel.getByRole('list', { name: 'Departures' })
  await expect(deps.getByRole('listitem').first()).toBeVisible({ timeout: 20000 })
  await expect(panel.getByRole('tab', { name: 'Departures' })).toHaveAttribute('aria-selected', 'true')
  const rows = await deps.getByRole('listitem').allInnerTexts()
  console.log(`departures ${rows.length}:\n${rows.slice(0, 6).join('\n---\n')}`)
  console.log(`panel foot: ${(await panel.innerText()).split('\n').slice(-6).join(' / ')}`)
  await step('Nørreport St. departures from the timetable')
  // every non-Metro row shows a planned time and the delay unknown
  const timed = rows.filter((r) => !/Every \d+ min/.test(r))
  expect(timed.length).toBeGreaterThan(0)
  for (const r of timed) {
    expect(r).toMatch(/\d\d:\d\d/)
    expect(r).toMatch(/—|Unknown/)
    expect(r).not.toMatch(/[+-]\d+\s*min|\+\d+\b/)
  }
  await panel.getByRole('tab', { name: 'Arrivals' }).click()
  await expect(page).toHaveURL(/board=arrivals/)
  const arr = panel.getByRole('list', { name: 'Arrivals' })
  await expect(arr.getByRole('listitem').first()).toBeVisible({ timeout: 20000 })
  const arows = await arr.getByRole('listitem').allInnerTexts()
  console.log(`arrivals ${arows.length}: ${arows.slice(0, 3).join(' | ')}`)
  console.log(`arrivals foot: ${(await panel.innerText()).split('\n').slice(-6).join(' / ')}`)
  await step('Nørreport St. arrivals from the timetable')
  // a trip opened from the Vehicles list: planned times, no delay
  await page.goto('/en?tab=vehicles')
  const table = page.getByRole('table', { name: 'Vehicles' })
  const link = table.locator('a[href*="trip=bus."]').nth(5)
  await link.click()
  const trip = page.getByRole('dialog', { name: / to / }).last()
  await expect(trip).toBeVisible()
  await expect(page).toHaveURL(/[?&]trip=/)
  const stops = trip.getByRole('list', { name: 'Stops' })
  await expect(stops).toBeVisible()
  const text = await trip.innerText()
  console.log(`trip panel: ${text.slice(0, 400).replace(/\n/g, ' / ')} ... ${text.slice(-120).replace(/\n/g, ' / ')}`)
  await expect(trip).toContainText('Timetable only')
  await expect(trip).toContainText(/Delay\s*—/)
  await expect(stops).toContainText(/\d\d:\d\d/)
  expect(text).not.toMatch(/On time|\+\d+ min|Expected/)
  await step('vehicle panel: planned times, delay unknown')
  const after = await (await page.request.get('/api/snapshot')).json()
  console.log(`after: calls ${JSON.stringify(after.status.calls)} budget ${JSON.stringify(after.budget)} api ${after.api.status} positionMode ${after.positionMode} disruptions ${after.disruptions} lastSeen ${JSON.stringify(after.lastSeen)}`)
  expect(after.status.calls).toEqual([])
  expect(after.budget).toEqual({ level: 'normal', calls: 0 })
}
