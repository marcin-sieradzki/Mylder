import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
export default async ({ page, step, expect }: Journey) => {
  const dots = page.locator('[data-vehicles]')
  await page.goto('/en?map=14.00/55.67600/12.56800/-30.0/50.0')
  await expect(dots).toHaveAttribute('data-tilt', '50')
  await expect(dots).toHaveAttribute('data-heading', '-30')
  await expect(page.getByText(/\d+\s(m|km)$/)).toBeHidden()
  const snap = await (await page.request.get('/api/snapshot')).json()
  await expect(dots).toHaveAttribute('data-vehicles', String(snap.trips.filter((t: any) => !t.cancelled).length))
  await step('tilted link')
  await page.goto('/en?map=13.00/55.67600/12.56800')
  await expect(dots).toHaveAttribute('data-tilt', '0')
  await page.getByRole('region', { name: 'Live map of Copenhagen' }).focus()
  for (let i = 0; i < 3; i++) await page.keyboard.press('Shift+ArrowUp')
  for (let i = 0; i < 3; i++) await page.keyboard.press('Shift+ArrowRight')
  await expect(dots).toHaveAttribute('data-tilt', '30')
  await expect(dots).toHaveAttribute('data-heading', '45')
  await expect(page).toHaveURL(/map=13\.00\/55\.67600\/12\.56800\/45\.0\/30\.0/)
  await step('tilted by keys')
  await page.reload()
  await expect(dots).toHaveAttribute('data-tilt', '30')
  await expect(dots).toHaveAttribute('data-heading', '45')
  await step('reloaded')
  await page.getByRole('button', { name: 'Centre the map' }).click()
  await expect(page).toHaveURL(/map=[\d.]+\/[\d.]+\/[\d.]+(&|$)/)
  await step('centred')
  await page.goto('/en?map=14.00/55.67600/12.56800/-30.0/75.0')
  await expect(dots).toHaveAttribute('data-heading', '-30')
  await expect(dots).toHaveAttribute('data-tilt', '0')
  await step('out of range tilt')
}
