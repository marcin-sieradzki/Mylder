import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
// Unchanged source: a stop's note and source line on the weekday recording.
export default async ({ page, step, expect }: Journey) => {
  const foot = async (p: any) => (await p.innerText()).split('\n').filter((l: string) => l.trim()).slice(-3).join(' / ')
  await page.goto('/en?stop=27532')
  const nr = page.getByRole('dialog', { name: 'Nørreport St.' })
  await expect(nr.getByRole('list', { name: 'Departures' }).getByRole('listitem').first()).toBeVisible({ timeout: 20000 })
  const rows = await nr.getByRole('list', { name: 'Departures' }).getByRole('listitem').allInnerTexts()
  console.log(`Nørreport departures foot: ${await foot(nr)}\nfirst rows: ${rows.slice(0, 4).map((r) => r.replace(/\n/g, ' / ')).join(' | ')}`)
  await expect(nr).toContainText("Countdowns use Rejseplanen's expected times where it has them; the rest use the timetable, and say so.")
  await expect(nr).toContainText('From the timetable')
  await expect(nr).not.toContainText(/Timetable\s·\s\d|live times aren't connected/)
  await step('Nørreport departures')
  await nr.getByRole('tab', { name: 'Arrivals' }).click()
  await expect(nr.getByText(/Timetable and positions \d\d:\d\d/)).toBeVisible({ timeout: 20000 })
  console.log(`Nørreport arrivals foot: ${await foot(nr)}`)
  await step('Nørreport arrivals')
  await page.goto('/en?stop=8600783')
  const syd = page.getByRole('dialog', { name: 'København Syd St.' })
  await expect(syd.getByText(/departures \d\d:\d\d/)).toBeVisible({ timeout: 20000 })
  console.log(`København Syd departures foot: ${await foot(syd)}`)
  await expect(syd).toContainText('Rejseplanen')
  await step('København Syd departures from the board')
  await page.goto('/en?stop=8603313')
  const bc = page.getByRole('dialog', { name: 'Bella Center St.' })
  await expect(bc.getByRole('list', { name: 'Departures' }).getByRole('listitem').first()).toBeVisible({ timeout: 20000 })
  console.log(`Bella Center rows: ${(await bc.getByRole('list', { name: 'Departures' }).getByRole('listitem').allInnerTexts()).map((r) => r.replace(/\n/g, ' / ')).join(' | ')}\nfoot: ${await foot(bc)}`)
  await expect(bc).toContainText(/Every \d+/)
  await step('Bella Center Metro interval')
  await page.goto('/da?stop=27532')
  const da = page.getByRole('dialog', { name: 'Nørreport St.' })
  await expect(da.getByRole('list', { name: 'Afgange' }).getByRole('listitem').first()).toBeVisible({ timeout: 20000 })
  console.log(`Nørreport da foot: ${await foot(da)}`)
  await expect(da).toContainText('Fra køreplanen')
  await step('Nørreport in Danish')
}
