import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
// stop-open from the map, stop-list, none standing, stop-arrivals, board arrivals, no arrivals, language, missing.
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/en?map=15.00/55.6925/12.58779')
  await expect(page.locator('[data-vehicles]')).not.toHaveAttribute('data-vehicles', '0', { timeout: 20000 })
  await step('map at Østerport St.')
  const ost = page.getByRole('dialog', { name: 'Østerport St.' })
  await expect(async () => {
    const vp = page.viewportSize()!
    await page.mouse.click(vp.width / 2, vp.height / 2)
    await expect(ost).toBeVisible({ timeout: 2000 })
  }).toPass({ timeout: 40000 })
  await expect(page).toHaveURL(/[?&]stop=8600650/)
  await expect(ost.getByRole('tab', { name: 'Departures' })).toHaveAttribute('aria-selected', 'true')
  await expect(ost.getByRole('list', { name: 'Departures' }).getByRole('listitem').first()).toBeVisible({ timeout: 20000 })
  await step('Østerport opened from its marker')
  const urls: string[] = []
  page.on('request', (r) => urls.push(r.url()))
  await page.goto('/en?stop=27532')
  const nr = page.getByRole('dialog', { name: 'Nørreport St.' })
  await expect(nr.getByRole('region', { name: 'At the platforms now' })).toContainText('No vehicle of the types shown is standing at the platforms now.', { timeout: 20000 })
  expect(urls.some((u) => u.endsWith('/arrivals'))).toBe(false)
  await step('Nørreport, none standing')
  await nr.getByRole('tab', { name: 'Arrivals' }).click()
  await expect(page).toHaveURL(/\?stop=27532&board=arrivals/)
  const list = nr.getByRole('tabpanel', { name: 'Arrivals' }).getByRole('list', { name: 'Arrivals' })
  await expect(list.getByRole('listitem').first()).toBeVisible({ timeout: 20000 })
  expect(urls.filter((u) => u.includes('/api/stops/27532/arrivals')).length).toBe(1)
  await expect(nr).toContainText('From the timetable')
  await expect(nr.getByText(/Timetable and positions \d\d:\d\d/)).toBeVisible()
  console.log(`Nørreport arrivals: ${(await list.getByRole('listitem').allInnerTexts()).slice(0, 3).map((r) => r.replace(/\n/g, ' / ')).join(' | ')}`)
  await step('Nørreport arrivals')
  await nr.getByRole('tab', { name: 'Departures' }).click()
  await expect(page).not.toHaveURL(/board=/)
  await expect(nr.getByRole('list', { name: 'Departures' })).toBeVisible()
  await page.goto('/en?stop=8600783&board=arrivals')
  const syd = page.getByRole('dialog', { name: 'København Syd St.' })
  await expect(syd.getByText(/arrivals \d\d:\d\d/)).toBeVisible({ timeout: 20000 })
  await expect(syd).toContainText("Countdowns use Rejseplanen's expected times where it has them; the rest use the timetable, and say so.")
  await expect(syd).not.toContainText('Timetable and positions')
  await expect(syd.getByText('Track 8').first()).toBeVisible()
  await expect(syd).toContainText('From Holte St.')
  await step('København Syd arrivals from the board')
  await page.goto('/en?stop=8600683&board=arrivals')
  const hil = page.getByRole('dialog', { name: 'Hillerød St.' })
  await expect(hil).toContainText('No arrivals in the next 30 minutes for the vehicle types shown.', { timeout: 20000 })
  await expect(hil.getByText(/Timetable and positions \d\d:\d\d/)).toBeVisible()
  await step('Hillerød no arrivals')
  await page.goto('/en?stop=27532')
  await expect(nr.getByRole('list', { name: 'Departures' })).toBeVisible({ timeout: 20000 })
  await page.getByRole('navigation', { name: 'Language' }).getByRole('link', { name: 'Dansk' }).click()
  await expect(page).toHaveURL(/\/da\?stop=27532/)
  await expect(page.getByRole('dialog', { name: 'Nørreport St.' }).getByRole('list', { name: 'Afgange' })).toBeVisible({ timeout: 20000 })
  await step('language switched, panel kept')
  await page.goto('/da?stop=27532&board=arrivals')
  const da = page.getByRole('dialog', { name: 'Nørreport St.' })
  await expect(da.getByRole('tab', { name: 'Ankomster' })).toHaveAttribute('aria-selected', 'true')
  await expect(da.getByRole('list', { name: 'Ankomster' })).toContainText('Fra ', { timeout: 20000 })
  await step('Danish arrivals')
  await page.goto('/en?stop=nowhere')
  await expect(page.getByRole('dialog', { name: 'Stop not found' })).toBeVisible()
  await step('stop not found')
}
