import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
// stop-standing, stop-arrivals (by link and keys), Metro arrivals: within the run's first three minutes.
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/en?stop=48645')
  const ref = page.getByRole('dialog', { name: 'Refshaleøen' })
  const standing = ref.getByRole('region', { name: 'At the platforms now' })
  await expect(standing).toContainText('991', { timeout: 20000 })
  await expect(standing).toContainText('Teglholmen')
  console.log(`standing: ${(await standing.innerText()).replace(/\n/g, ' / ')}`)
  await step('Refshaleøen standing 991')
  await standing.getByRole('button', { name: 'Bus 991 to Teglholmen' }).click()
  await expect(page.getByRole('dialog', { name: /991 to Teglholmen/ })).toBeVisible()
  await expect(page).toHaveURL(/[?&]trip=/)
  await expect(page).not.toHaveURL(/[?&]stop=/)
  await step('standing trip opened')
  await page.goto('/en?stop=48645&board=arrivals')
  const arr = ref.getByRole('list', { name: 'Arrivals' })
  await expect(arr).toContainText('From Orientkaj St.', { timeout: 20000 })
  const row = (await arr.getByRole('listitem').allInnerTexts()).find((r) => /991/.test(r) && /Orientkaj/.test(r))
  console.log(`991 arrival row: ${row?.replace(/\n/g, ' / ')}`)
  expect(row).toMatch(/Timetable only|Live/)
  await expect(ref.getByRole('button', { name: 'Bus 991 from Orientkaj St.' }).first()).toBeVisible()
  await step('Refshaleøen arrivals by link')
  await ref.getByRole('tab', { name: 'Arrivals' }).focus()
  await page.keyboard.press('ArrowLeft')
  await expect(ref.getByRole('tab', { name: 'Departures' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page).not.toHaveURL(/board=/)
  await expect(ref.getByRole('tab', { name: 'Departures' })).toHaveAttribute('aria-selected', 'true')
  await step('keys back to Departures')
  await page.goto('/en?stop=8603313&board=arrivals')
  const bc = page.getByRole('dialog', { name: 'Bella Center St.' })
  const brow = bc.getByRole('list', { name: 'Arrivals' }).getByRole('listitem').first()
  await expect(brow).toContainText('M1', { timeout: 20000 })
  await expect(brow).toContainText('From Vanløse St.')
  await expect(brow).toContainText(/Every \d+ min/)
  await expect(brow).toContainText('Metro: planned times')
  expect(await brow.innerText()).not.toMatch(/\d\d:\d\d/)
  await step('Bella Center Metro arrivals')
}
