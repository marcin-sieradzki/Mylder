import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
import { findDot } from './lib.ts'
// trip-open by link, trip-follow and trip-line at a tilted, turned map; trip-open from a dot.
export default async ({ page, step, expect }: Journey) => {
  const snap = await (await page.request.get('/api/snapshot')).json()
  const t = snap.trips.find((x: any) => x.mode === 'bus' && !x.waiting)
  await page.goto(`/en?map=14.00/${t.position[0]}/${t.position[1]}/-30.0/50.0&trip=${t.key}`)
  const panel = page.getByRole('dialog', { name: new RegExp(`to ${t.headsign.replace(/[()]/g, '.')}`) })
  await expect(panel).toBeVisible({ timeout: 20000 })
  await expect(panel).toContainText('Delay')
  await expect(panel).toContainText('Last seen')
  await expect(panel).toContainText('Next stop')
  const text = await panel.innerText()
  console.log(`source line: ${text.split('\n').filter((l) => /·/.test(l)).pop()}`)
  await step('trip by link, tilted')
  await panel.getByRole('button', { name: 'Follow' }).click()
  await page.waitForTimeout(3000)
  const map = page.locator('[data-vehicles]')
  const card = await findDot(page)
  console.log(`card on follow: ${card?.text}`)
  expect(card?.text).toContain(t.line)
  await expect(map).toHaveAttribute('data-tilt', '50')
  await expect(map).toHaveAttribute('data-heading', '-30')
  await step('following, tilted')
  await panel.getByRole('button', { name: 'Show whole line' }).click()
  const chip = page.getByRole('button', { name: /^Showing: line .* · Clear$/ })
  await expect(chip).toBeVisible()
  await expect.poll(() => Number(new URL(page.url()).searchParams.get('map')!.split('/')[0]), { timeout: 10000 }).toBeLessThan(14)
  await page.waitForTimeout(1500)
  expect(new URL(page.url()).searchParams.get('map')).toMatch(/\/-30\.0\/50\.0$/)
  await step('whole line, tilted')
  await chip.click()
  await expect(chip).toBeHidden()
}
