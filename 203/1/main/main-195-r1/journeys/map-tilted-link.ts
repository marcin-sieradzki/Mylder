import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/en?map=14.00/55.67600/12.56800/-30.0/50.0')
  const v = page.locator('[data-vehicles]')
  await expect(v).toHaveAttribute('data-tilt', '50', { timeout: 20000 })
  await expect(v).toHaveAttribute('data-heading', '-30')
  await expect(page.getByText(/\d+\s(m|km)$/)).toBeHidden()
  await step('tilted link')
  await page.goto('/en?map=13.00/55.67600/12.56800')
  await expect(v).not.toHaveAttribute('data-vehicles', '0', { timeout: 20000 })
  await page.getByRole('region', { name: 'Live map of Copenhagen' }).focus()
  for (let i = 0; i < 3; i++) await page.keyboard.press('Shift+ArrowUp')
  for (let i = 0; i < 3; i++) await page.keyboard.press('Shift+ArrowRight')
  await expect(v).toHaveAttribute('data-tilt', '30')
  await expect(v).toHaveAttribute('data-heading', '45')
  await expect(page).toHaveURL(/map=13\.00\/55\.67600\/12\.56800\/45\.0\/30\.0/)
  await step('tilted by keys')
  await page.reload()
  await expect(v).toHaveAttribute('data-tilt', '30', { timeout: 20000 })
  await expect(v).toHaveAttribute('data-heading', '45')
  await step('reloaded')
}
