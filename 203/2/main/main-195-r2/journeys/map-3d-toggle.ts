import type { Journey } from '../../../.claude/skills/verify-mylder/scripts/drive.ts'
export default async ({ page, step, expect }: Journey) => {
  await page.goto('/en')
  const v = page.locator('[data-vehicles]')
  await expect(v).not.toHaveAttribute('data-vehicles', '0', { timeout: 20000 })
  const toggle = page.getByRole('button', { name: '3D view' })
  await step('flat')
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await expect(v).toHaveAttribute('data-tilt', '50')
  await expect(page.getByText(/\d+\s(m|km)$/)).toBeHidden()
  await step('3d on')
  await page.getByRole('region', { name: 'Live map of Copenhagen' }).focus()
  await page.keyboard.press('Shift+ArrowRight')
  await expect(v).toHaveAttribute('data-heading', '15')
  const north = page.getByRole('button', { name: 'Reset to north' })
  await expect(north).toHaveAccessibleDescription('Map turned away from north')
  await step('turned')
  await north.click()
  await expect(v).toHaveAttribute('data-heading', '0')
  await expect(v).toHaveAttribute('data-tilt', '50')
  await step('north')
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await expect(page.getByText(/\d+\s(m|km)$/)).toBeVisible()
  await step('flat again')
}
